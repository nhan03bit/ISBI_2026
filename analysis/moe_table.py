"""LaTeX table + macros for the MoE (non-entropy) comparison in docs/paper/isbi_submit.

Reads analysis/out/moe_compare.json (analysis/moe_compare.py) and writes
  analysis/out/moe_baseline_table.tex, moe_baseline_macros.tex
and copies them to docs/paper/isbi_submit/generated/ (the paper never types a result by hand).
Rows are flip-TTA SWA checkpoints on the 17,270 internal-val images:
  2-seed 768 px (probability average of seeds 42 and 1024), fixed 4-model average
  (768 s42, 768 s1024, 896 s86, 1024 s86) and the mean +- s.d. of those four single models.

    python -I analysis/moe_table.py
"""
import json
import statistics as st
from pathlib import Path

ROOT = Path("/home/psytp7/ISBI_2026")
OUT = ROOT / "analysis/out"
GEN = ROOT / "docs/paper/isbi_submit/generated"
d = json.load(open(OUT / "moe_compare.json"))
P, PAIRS = d["point"], d["pairs"]
assert not d["missing"], d["missing"]
M = ("mAP", "mAUC", "mF1", "mECE")
SINGLES = ("768 s42", "768 s1024", "896 s86", "1024 s86")


def f3(x): return f"{x:.3f}"


def single_mean(prefix):
    return {m: (st.mean(P[f"{prefix} {s}"][m] for s in SINGLES),
                st.stdev(P[f"{prefix} {s}"][m] for s in SINGLES)) for m in M}


def row(label, vals, sd=None):
    cells = [f3(vals[m]) if sd is None else f"{f3(vals[m][0])}{{\\scriptsize$\\pm${f3(vals[m][1])}}}" for m in M]
    return f"{label} & " + " & ".join(cells) + " \\\\"


names = {"ASL": "ASL only", "MoE": "MoE", "TM": "Entropy gate"}
rows = ["% generated by analysis/moe_table.py from moe_compare.json -- do not edit",
        "% columns: setting/method & mAP & mAUC & mF1 & mECE",
        "\\emph{2 seeds, 768~px} & & & & \\\\"]
for k in ("ASL", "MoE", "TM"):
    rows.append(row(names[k], P[f"{k} 2-seed 768"]))
rows.append("\\emph{4 models, 768--1024~px} & & & & \\\\")
for k in ("MoE", "TM"):
    rows.append(row(names[k], P[f"{k} fixed 4-model"]))
rows.append("\\emph{those 4, single models} & & & & \\\\")
for k in ("MoE", "TM"):
    rows.append(row(names[k], {m: v[0] for m, v in single_mean(k).items()}))

# the whole tabular is generated: a row-final "\\\\" must not be followed by \\else inside a tabular
TOP = ["\\begin{tabular}{lcccc}", "\\toprule", " & mAP & mAUC & mF1 & mECE \\\\", "\\midrule"]
BOT = ["\\bottomrule", "\\end{tabular}"]
mac = ["% generated by analysis/moe_table.py -- do not edit"]


def pair(tag, key):
    for m, nm in (("mAP", "MAP"), ("mECE", "MECE")):
        p = PAIRS[key][m]
        mac.append(f"\\newcommand{{\\{tag}{nm}}}{{{p['point']:+.4f}}}")
        mac.append(f"\\newcommand{{\\{tag}{nm}lo}}{{{p['ci'][0]:+.4f}}}")
        mac.append(f"\\newcommand{{\\{tag}{nm}hi}}{{{p['ci'][1]:+.4f}}}")


pair("MoeTmMoe", "TM 2-seed 768 - MoE 2-seed 768")
pair("MoeTmAsl", "TM 2-seed 768 - ASL 2-seed 768")
pair("MoeMoeAsl", "MoE 2-seed 768 - ASL 2-seed 768")
pair("MoeTmMoeFour", "TM fixed 4-model - MoE fixed 4-model")

for p in (OUT, GEN):
    p.mkdir(parents=True, exist_ok=True)
    (p / "moe_baseline_table.tex").write_text("\n".join(TOP + rows + BOT) + "\n")
    (p / "moe_baseline_macros.tex").write_text("\n".join(mac) + "\n")
print("\n".join(rows)); print("\n".join(mac))
