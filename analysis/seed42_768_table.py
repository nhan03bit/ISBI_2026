"""Table 1 variant for the paper: 768 px, seed 42, single run per system (2026-10-14).

Reads the per-run metrics of analysis/unified_benchmark.py (analysis/out/unified_benchmark.json;
SWA weights, horizontal-flip TTA, 17,270 internal-validation images) and writes
docs/paper/isbi_submit/generated/seed42_768_table.tex with the four rows of Table 1.
Arms: A = ASL only, C = Triplet Memory + Entropy, Dwith / Dzero = + Markov prior, history available / withheld.

    python3 -I analysis/seed42_768_table.py
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "analysis/out/unified_benchmark.json"
OUT = ROOT / "docs/paper/isbi_submit/generated/seed42_768_table.tex"
SEED = "42"
COLS = ("mAP", "mAUC", "mF1", "mECE", "head", "medium", "tail")
ROWS = [
    ("ASL only (asymmetric loss)", "A"),
    ("Triplet Memory + Entropy", "C"),
    ("Triplet Memory + Entropy + Markov prior, history available", "Dwith"),
    ("Triplet Memory + Entropy + Markov prior, history withheld", "Dzero"),
]

runs = json.loads(SRC.read_text())["runs"]
lines = [f"% generated by analysis/seed42_768_table.py from {SRC.name} -- do not edit",
         "% columns: system & n & mAP & mAUC & mF1 & mECE & head AP & medium AP & tail AP"]
for label, arm in ROWS:
    r = runs[arm][SEED]
    cells = ["1", *[f"{r[c]:.3f}" for c in COLS]]
    lines.append(f"{label} & " + " & ".join(cells) + " \\\\")
lines[-1] = lines[-1].rstrip(" \\")   # paper.tex adds the final row break itself
OUT.write_text("\n".join(lines) + "\n")
print("\n".join(lines))
