"""Table 1 variant for the paper: 512 px, seed 42, single run per system (2026-10-14).

Reads the per-run metrics already computed by analysis/entropy_ablation.py (analysis/out/entropy_ablation.json;
EMA weights of the best epoch, no SWA, no TTA, 17,270 internal-validation images) and writes
docs/paper/isbi_submit/generated/seed42_512_table.tex with the four rows of Table 1.
ASL only = ablation512/asl seed 42; Triplet Memory + Entropy = seedsweep seed 42 (arm "gate").
The Markov-prior runs exist at 768 px only, so those two rows are left as dashes; nothing is imputed.

    python3 -I analysis/seed42_512_table.py
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "analysis/out/entropy_ablation.json"
OUT = ROOT / "docs/paper/isbi_submit/generated/seed42_512_table.tex"
SEED = "42"
COLS = ("mAP", "mAUC", "mF1", "mECE", "head", "medium", "tail")
ROWS = [
    ("ASL only (asymmetric loss)", "asl"),
    ("Triplet Memory + Entropy", "gate"),
    ("Triplet Memory + Entropy + Markov prior, history available", None),
    ("Triplet Memory + Entropy + Markov prior, history withheld", None),
]

runs = json.loads(SRC.read_text())["runs"]
lines = [f"% generated by analysis/seed42_512_table.py from {SRC.name} -- do not edit",
         "% columns: system & n & mAP & mAUC & mF1 & mECE & head AP & medium AP & tail AP"]
for label, arm in ROWS:
    if arm is None:
        cells = ["--", *["--"] * len(COLS)]
    else:
        r = runs[arm][SEED]
        cells = ["1", *[f"{r[c]:.3f}" for c in COLS]]
    lines.append(f"{label} & " + " & ".join(cells) + " \\\\")
lines[-1] = lines[-1].rstrip(" \\")   # paper.tex adds the final row break itself
OUT.write_text("\n".join(lines) + "\n")
print("\n".join(lines))
